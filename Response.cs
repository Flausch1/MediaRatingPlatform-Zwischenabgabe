using System;
using System.Collections.Generic;
using System.Net;
using System.Text;

namespace HttpServerDemo
{
    internal class Response
    {
        private HttpListenerResponse response;

        public Response(HttpListenerResponse response)
        {
            this.response = response;
        }

        public async Task SendResponse(int statusCode, string contentType, string body)
        {
            var bytes = Encoding.UTF8.GetBytes(body);

            response.StatusCode = statusCode;
            response.ContentType = contentType;
            response.ContentLength64 = bytes.Length;

            printResponse(body);

            await response.OutputStream.WriteAsync(bytes, 0, bytes.Length);
            response.Close();
        }

        private void printResponse(string body)
        {
            Console.WriteLine($"---------- Send response ----------");
            Console.WriteLine($"HTTP/{response.ProtocolVersion} {response.StatusCode} {response.StatusDescription}");
            foreach (string header in response.Headers)
            {
                Console.WriteLine($"{header}: {response.Headers[header]}");
            }
            Console.WriteLine($"Content Length: {response.ContentLength64}");   // this header is automatically generated by HttpListener
            Console.WriteLine();
            Console.WriteLine(body);
        }
    }
}
